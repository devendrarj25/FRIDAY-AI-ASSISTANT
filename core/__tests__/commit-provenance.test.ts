/**
 * Commit provenance is checked on a throwaway repo, never this checkout's history.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { describe, expect, it } from "vitest";

const require_ = createRequire(import.meta.url);
const IDENTITY = require_(path.resolve(process.cwd(), "scripts/identity.cjs")) as {
  GITHUB: string;
  OWNER: string;
};

const script = path.resolve(process.cwd(), "scripts/check-provenance.cjs");

function git(dir: string, args: string[]) {
  execFileSync("git", args, { cwd: dir, stdio: "ignore" });
}

function repo(): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "friday-provenance-"));
  git(dir, ["init", "-b", "main"]);
  git(dir, ["config", "user.name", IDENTITY.OWNER]);
  git(dir, ["config", "user.email", `${IDENTITY.GITHUB}@users.noreply.github.com`]);
  fs.writeFileSync(path.join(dir, "README.md"), "FRIDAY\n");
  git(dir, ["add", "README.md"]);
  git(dir, ["commit", "-m", "feat: keep the desk on this PC"]);
  git(dir, ["tag", "base"]);
  return dir;
}

function commit(
  dir: string,
  message: string,
  author?: string,
  committer?: { name: string; email: string },
) {
  fs.appendFileSync(path.join(dir, "README.md"), `${message}\n`);
  git(dir, ["add", "README.md"]);
  const args = ["commit", "-m", message];
  if (committer) {
    args.unshift("-c", `user.email=${committer.email}`);
    args.unshift("-c", `user.name=${committer.name}`);
  }
  if (author) args.push(`--author=${author}`);
  git(dir, args);
}

const DEPENDABOT_EMAIL = "49699333+dependabot[bot]@users.noreply.github.com";
const DEPENDABOT = `dependabot[bot] <${DEPENDABOT_EMAIL}>`;

function check(dir: string): { status: number; out: string } {
  try {
    const out = execFileSync(process.execPath, [script, "base"], {
      cwd: dir,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
    return { status: 0, out };
  } catch (error) {
    const err = error as { status?: number; stdout?: string; stderr?: string };
    return { status: err.status ?? 1, out: `${err.stdout || ""}${err.stderr || ""}` };
  }
}

describe("commit provenance", () => {
  it("accepts the owner and the repository automation identities", () => {
    const dir = repo();
    commit(dir, "fix: repair the local pack");
    commit(dir, "ci: sync docs", "friday-ci <friday-ci@users.noreply.github.com>");
    commit(
      dir,
      "safety: preserve unexpected main push",
      "FRIDAY Main Safety <actions@users.noreply.github.com>",
    );
    commit(dir, "feat: note a human review\n\nCo-authored-by: devendrarj25");
    const result = check(dir);
    expect(result.status).toBe(0);
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("rejects an assistant author, co-author, generated mark, or other bot", () => {
    const cases: {
      message: string;
      author?: string;
      committer?: { name: string; email: string };
    }[] = [
      {
        message: "feat: desk",
        author: "Cursor Agent <cursoragent@cursor.com>",
      },
      {
        message: "feat: desk\n\nCo-authored-by: Claude <noreply@anthropic.com>",
      },
      {
        message: "feat: desk\n\nGenerated with Cursor",
      },
      {
        message: "feat: desk\n\nClaude-Session: https://claude.ai/code/session_abc",
      },
      {
        message: "feat: desk\n\nGenerated by Claude Code",
      },
      {
        message: "feat: desk\n\nsee https://claude.ai/code/session_abc",
      },
      {
        message: "feat: desk",
        author: "dependabot[bot] <dependabot[bot]@users.noreply.github.com>",
      },
      {
        message: "feat: desk",
        author: "dependabot[bot] <support@github.com>",
        committer: { name: "dependabot[bot]", email: "support@github.com" },
      },
      {
        message: "feat: desk\n\nCo-authored-by: dependabot[bot] <other@example.com>",
      },
      {
        message: `feat: desk\n\nCo-authored-by: dependabot[bot] <${DEPENDABOT_EMAIL}.evil>`,
      },
      {
        message: `feat: desk\n\nCo-authored-by: Someone <${DEPENDABOT_EMAIL}>`,
      },
      {
        message: "feat: desk",
        author: "copilot[bot] <49699333+copilot[bot]@users.noreply.github.com>",
      },
      {
        message: "feat: desk",
        author: "cursor[bot] <cursor[bot]@users.noreply.github.com>",
      },
      {
        message: "feat: desk",
        author: "claude[bot] <claude[bot]@users.noreply.github.com>",
      },
    ];
    for (const row of cases) {
      const dir = repo();
      commit(dir, row.message, row.author, row.committer);
      const result = check(dir);
      expect(result.status, row.message).toBe(1);
      fs.rmSync(dir, { recursive: true, force: true });
    }
  }, 120_000);

  it("accepts the dependency-update account only with its exact email", () => {
    const dir = repo();
    commit(
      dir,
      "chore: bump a dev package\n\nSigned-off-by: dependabot[bot] <support@github.com>",
      DEPENDABOT,
      { name: "dependabot[bot]", email: DEPENDABOT_EMAIL },
    );
    commit(dir, `chore: record the same account\n\nCo-authored-by: ${DEPENDABOT}`);
    const result = check(dir);
    expect(result.status, result.out).toBe(0);
    const scope = require_(path.resolve(process.cwd(), "scripts/pr-scope.cjs")) as {
      isDocsOnly: (files: string[]) => boolean;
    };
    expect(scope.isDocsOnly(["package.json", "package-lock.json", "kernel/requirements.txt"])).toBe(
      false,
    );
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("judges the pull request title and body for an assistant's credit, not for product names", () => {
    const { textProblems } = require_(script) as {
      textProblems: (label: string, text: string) => string[];
    };
    // A footer, an emoji credit, a session link or a co-author line is refused.
    expect(textProblems("body", "Fixes the build.\n\nGenerated with Claude Code").length).toBe(1);
    expect(textProblems("body", "done by 🤖").length).toBe(1);
    expect(textProblems("body", "https://claude.ai/code/session_x").length).toBe(1);
    expect(
      textProblems("body", "Co-authored-by: Claude <noreply@anthropic.com>").length,
    ).toBeGreaterThan(0);
    // A change about model providers, or about generated files, is fine.
    expect(textProblems("body", "Adds the Claude and Gemini providers to the router.")).toEqual([]);
    expect(textProblems("body", "The docs map is generated with npm run docs:sync.")).toEqual([]);
    expect(textProblems("title", "")).toEqual([]);
  });

  it("reads the pull request text from the environment and fails the run on a credit", () => {
    const dir = repo();
    commit(dir, "feat: a clean change");
    const run = (env: Record<string, string>) => {
      try {
        const out = execFileSync(process.execPath, [script, "base"], {
          cwd: dir,
          encoding: "utf8",
          env: { ...process.env, ...env },
          stdio: ["ignore", "pipe", "pipe"],
        });
        return { status: 0, out };
      } catch (error) {
        const err = error as { status?: number; stdout?: string; stderr?: string };
        return { status: err.status ?? 1, out: `${err.stdout || ""}${err.stderr || ""}` };
      }
    };
    expect(run({ PR_TITLE: "feat: clean", PR_BODY: "A plain description." }).status).toBe(0);
    const bad = run({ PR_TITLE: "feat: clean", PR_BODY: "text\n\n🤖 Generated with Claude Code" });
    expect(bad.status).toBe(1);
    expect(bad.out).toContain("pull request body");
    fs.rmSync(dir, { recursive: true, force: true });
  });
});

describe("the commit-msg hook", () => {
  const hook = path.resolve(process.cwd(), "scripts/git-hooks/commit-msg");
  const run = (message: string) => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "friday-hook-"));
    const file = path.join(dir, "MSG");
    fs.writeFileSync(file, message);
    try {
      execFileSync("sh", [hook, file], { stdio: "pipe" });
      return 0;
    } catch (error) {
      return (error as { status: number }).status;
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  };

  it("lets a clean Conventional Commit through", () => {
    expect(run("fix: keep the desk on this PC\n\nA short body.\n")).toBe(0);
  });

  it("refuses a session trailer, a generated line and a tool co-author", () => {
    expect(run("fix: x\n\nClaude-Session: https://claude.ai/code/session_abc\n")).toBe(1);
    expect(run("fix: x\n\nGenerated by Claude Code\n")).toBe(1);
    expect(run("fix: x\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n")).toBe(1);
  });
});

describe("bots and release notes", () => {
  const GH_BOT = "github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>";

  it("accepts a change merged or edited on github.com, and still refuses the workflow bot", () => {
    const dir = repo();
    commit(
      dir,
      "docs: edit on the web",
      "DeVeNdrA <311363093+devendrarj25@users.noreply.github.com>",
      {
        name: "GitHub",
        email: "noreply@github.com",
      },
    );
    expect(check(dir).status).toBe(0);
    commit(
      dir,
      "chore: sync",
      "github-actions[bot] <41898282+github-actions[bot]@users.noreply.github.com>",
    );
    expect(check(dir).status).toBe(1);
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("does not fail a commit for prose that says something was generated with a tool command", () => {
    const dir = repo();
    commit(dir, "docs: the map is generated with npm run docs:sync");
    expect(check(dir).status).toBe(0);
    fs.rmSync(dir, { recursive: true, force: true });
  });

  it("lets a dependency update quote release notes, but still refuses a tool co-author", () => {
    const dir = repo();
    commit(
      dir,
      "chore(deps): bump a package\n\nRelease notes\n🤖 I have created a release\nGenerated with a docs tool",
      DEPENDABOT,
      { name: "dependabot[bot]", email: DEPENDABOT_EMAIL },
    );
    const run = (env: Record<string, string>) => {
      try {
        execFileSync(process.execPath, [script, "base"], {
          cwd: dir,
          encoding: "utf8",
          env: { ...process.env, ...env },
          stdio: ["ignore", "pipe", "pipe"],
        });
        return 0;
      } catch (error) {
        return (error as { status: number }).status;
      }
    };
    expect(run({ PR_TITLE: "chore(deps): bump a package", PR_BODY: "🤖 release notes" })).toBe(0);
    expect(run({ PR_BODY: "Co-authored-by: Claude <noreply@anthropic.com>" })).toBe(1);
    commit(dir, "feat: owner change\n\nGenerated by Claude Code");
    expect(run({})).toBe(1);
    fs.rmSync(dir, { recursive: true, force: true });
  });
});
