/** The leading word of a label, letters only, lower case. */
export function leadingVerb(label: string): string {
  const word = label.trim().split(/\s+/)[0] ?? "";
  return word.replace(/[^A-Za-z]/g, "").toLowerCase();
}

/** The icon for a button label, or null when the label is not one we know. */
export function iconForLabel(label: string): LucideIcon | null {
  const verb = leadingVerb(label);
  if (!verb) return null;
  return Object.prototype.hasOwnProperty.call(VERBS, verb) ? (VERBS[verb] ?? null) : null;
}

