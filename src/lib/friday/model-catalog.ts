/** The provider-side id for a model — its own `apiId`, the map, then the id. */
export function apiIdFor(model: ModelSpec): string {
  return model.apiId ?? API_IDS[model.id] ?? model.id;
}

/**
 * Every string that can identify one catalog model on the routing side:
 * the provider API id (cloud), the registry tag (Ollama) and the catalog id.
 * The desktop matcher tries them in order, so a pinned model resolves whether
 * it runs locally or on a provider.
 */
export function routeRefs(ids: string[]): string[] {
  const out: string[] = [];
  const seen = new Set<string>();
  const add = (value: string | null | undefined) => {
    if (!value || seen.has(value)) return;
    seen.add(value);
    out.push(value);
  };
  for (const id of ids) {
    const model = modelById.get(id);
    if (!model) {
      add(id);
      continue;
    }
    if (model.kind === "cloud") add(apiIdFor(model));
    else add(registryTag(model));
    add(id);
  }
  return out;
}
