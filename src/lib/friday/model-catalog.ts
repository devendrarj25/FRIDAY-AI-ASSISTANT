const M = (
  id: string,
  name: string,
  provider: ProviderId,
  category: ModelCategory,
  params: string,
  sizeGb: number,
  ctxK: number,
  vramGb: number,
  license: string,
  url: string,
  version: string,
  caps: Capability[],
  extra: Partial<ModelSpec> = {},
): ModelSpec => {
  const kind = providerById.get(provider)?.kind ?? "local";
  return {
    id,
    name,
    provider,
    category,
    kind,
    params,
    quant: extra.quant ?? (kind === "local" ? "Q4_K_M" : "—"),
    format: extra.format ?? (kind === "local" ? "GGUF" : "API"),
    sizeGb,
    ctxK,
    vramGb,
    ramGb: extra.ramGb ?? Math.max(4, Math.round(sizeGb * 1.5)),
    license,
    source: providerById.get(provider)?.name ?? provider,
    url,
    version,
    caps,
    installed: extra.installed ?? null,
    ...extra,
  };
};

