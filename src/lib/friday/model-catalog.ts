/* --------------------------------------------------------- registry naming */

/**
 * The real registry tag a model is pulled and run under.
 *
 * Ollama entries carry their library slug in `url` (ollama.com/library/<slug>);
 * combined with the parameter size that yields the exact tag the daemon uses,
 * e.g. `llama3.1:8b`. Cloud models are addressed by their API id, which is the
 * catalog id itself.
 */
export function registryTag(model: ModelSpec): string | null {
  if (model.provider === "ollama") {
    const slug = /ollama\.com\/library\/([^/?#]+)/i.exec(model.url)?.[1];
    if (!slug) return null;
    if (slug.includes(":")) return slug;
    const size = model.params.trim().toLowerCase().replace(/\s+/g, "");
    return size && size !== "—" ? `${slug}:${size}` : slug;
  }
  return null;
}

/** Match a real installed tag (`llama3.1:8b`) back to a catalog entry. */
export function modelByTag(tag: string): ModelSpec | null {
  const normalized = tag.trim().toLowerCase();
  const bare = normalized.replace(/:latest$/, "");
  for (const model of modelCatalog) {
    const t = registryTag(model)?.toLowerCase();
    if (!t) continue;
    if (t === normalized || t === bare || t.split(":")[0] === bare) return model;
  }
  return null;
}

