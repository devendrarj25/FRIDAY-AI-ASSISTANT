export type SupportLevel = "Optimal" | "Supported" | "Tight" | "CPU only" | "Unsupported";

export type SupportCheck = {
  level: SupportLevel;
  reason: string;
  tone: "accent" | "primary" | "warning" | "destructive" | "muted";
};

export function checkSupport(model: ModelSpec, sys: SystemProfile): SupportCheck {
  if (model.kind === "cloud")
    return {
      level: "Supported",
      reason: "hosted — runs on the provider, only needs a key and network",
      tone: "primary",
    };
  if (model.sizeGb > sys.diskFreeGb)
    return {
      level: "Unsupported",
      reason: `needs ${model.sizeGb} GB free disk, ${sys.diskFreeGb} GB available`,
      tone: "destructive",
    };
  if (model.ramGb > sys.ramGb)
    return {
      level: "Unsupported",
      reason: `needs ~${model.ramGb} GB RAM, system has ${sys.ramGb} GB`,
      tone: "destructive",
    };
  if (model.vramGb === 0)
    return { level: "Optimal", reason: "CPU-friendly workload", tone: "accent" };
  if (sys.vramGb === 0)
    return {
      level: "CPU only",
      reason: "no GPU detected — will run on CPU, expect low tokens/sec",
      tone: "warning",
    };
  if (model.vramGb <= sys.vramGb * 0.75)
    return { level: "Optimal", reason: `fits fully in ${sys.vramGb} GB VRAM`, tone: "accent" };
  if (model.vramGb <= sys.vramGb)
    return {
      level: "Supported",
      reason: `close to the ${sys.vramGb} GB VRAM limit — keep context modest`,
      tone: "primary",
    };
  if (model.vramGb <= sys.vramGb + sys.ramGb * 0.5)
    return {
      level: "Tight",
      reason: `needs ${model.vramGb} GB VRAM — will offload layers to RAM`,
      tone: "warning",
    };
  return {
    level: "Unsupported",
    reason: `needs ${model.vramGb} GB VRAM, only ${sys.vramGb} GB present`,
    tone: "destructive",
  };
}

