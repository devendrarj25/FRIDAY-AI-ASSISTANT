/**
 * FRIDAY master AI models & providers catalog.
 *
 * Every local entry points at the vendor's own distribution (Ollama library,
 * Hugging Face repo, GitHub release) — FRIDAY never pulls from mirrors. Cloud
 * entries carry the provider's official API base and use your own key.
 *
 * This module is pure data + pure helpers; all runtime state lives in
 * models-engine.ts.
 */

