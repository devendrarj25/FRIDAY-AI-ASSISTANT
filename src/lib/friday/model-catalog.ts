export type Provider = {
  id: ProviderId;
  name: string;
  kind: ProviderKind;
  transport: "openai" | "native" | "runtime" | "integration";
  endpoint: string;
  docs: string;
  auth: "none" | "api-key" | "cloud-iam";
  detect: string;
  notes: string;
};

export type ModelCategory =
  | "Chat"
  | "Reasoning"
  | "Coding"
  | "Vision"
  | "Multimodal"
  | "Image"
  | "Speech to Text"
  | "Text to Speech"
  | "Embedding"
  | "Reranking";

export type ModelFormat =
  "GGUF" | "Safetensors" | "ONNX" | "PyTorch" | "TensorFlow" | "MLX" | "API";

export type Capability = "stream" | "tools" | "vision" | "audio" | "json";

export type ModelSpec = {
  id: string;
  name: string;
  provider: ProviderId;
  category: ModelCategory;
  kind: ProviderKind;
  params: string;
  quant: string;
  format: ModelFormat;
  sizeGb: number;
  ctxK: number;
  /** Minimum VRAM for a comfortable GPU load; 0 = CPU friendly / hosted. */
  vramGb: number;
  ramGb: number;
  license: string;
  source: string;
  url: string;
  version: string;
  caps: Capability[];
  /** Pre-seeded local installs so the preview has a realistic starting state. */
  installed?: string | null;
  /**
   * The id this model is really addressed by on its provider's API
   * (`meta/llama-3.3-70b-instruct`, `Qwen/Qwen3-Coder-480B-A35B-Instruct`, …).
   * Cloud entries need it because the catalog id is a short human handle.
   */
  apiId?: string;
};

