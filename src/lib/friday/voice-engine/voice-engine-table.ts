/**
 * FRIDAY · the data of the voice engine registry (rules and types: `voice-engine-registry.ts`).
 *
 * One row per engine FRIDAY uses or may use. The facts were read on 2026-11-23 from the Hugging Face model API (file
 * sizes and LFS digests at the revision named in the evidence line) and the model cards; a number that no run measured
 * says `estimated`. A pinned engine repeats none of its memory or disk numbers (the model catalogue holds them, and a
 * test keeps them equal to electron/voice-pins.cjs); an engine that is not pinned lists its exact files here.
 * A row is `usable` only with a wrapper and a self-test (see `unusableReason`); a candidate says what is missing.
 */
import type {
  EngineFile,
  EngineFacts,
  VoiceEngine,
  VoiceLang,
  VoiceRole,
} from "./voice-engine-registry";

const HF = (repo: string, note = "") =>
  `https://huggingface.co/${repo}${note ? ` (${note}, read 2026-11-23)` : " (read 2026-11-23)"}`;

type Row = Partial<VoiceEngine> &
  Pick<VoiceEngine, "id" | "label" | "role" | "languages" | "runtime" | "torchFree" | "status"> & {
    code: string;
    weights: string;
    lat: VoiceEngine["latency"];
  };

const row = (r: Row): VoiceEngine => {
  const { code, weights, lat, ...rest } = r;
  return {
    repo: null,
    pinRepo: null,
    files: null,
    facts: null,
    streaming: false,
    flags: [],
    wrapper: null,
    selfTest: false,
    blockedBy: "",
    evidence: [],
    ...rest,
    codeLicence: code,
    weightLicence: weights,
    latency: lat,
  };
};

const L = (
  hi: VoiceEngine["languages"]["hi"],
  en: VoiceEngine["languages"]["en"],
  hinglish: VoiceEngine["languages"]["hinglish"],
) => ({
  hi,
  en,
  hinglish,
});
const file = (name: string, bytes: number, sha256: string | null = null): EngineFile => ({
  name,
  bytes,
  sha256,
});
const sum = (files: EngineFile[]) => files.reduce((total, f) => total + f.bytes, 0);
const est = (
  minRamGb: number,
  recommendedRamGb: number,
  minVramGb: number,
  files: EngineFile[],
  cpuOk: boolean,
  gpuOk: boolean,
): EngineFacts => ({
  minRamGb,
  recommendedRamGb,
  minVramGb,
  diskBytes: sum(files),
  cpuOk,
  gpuOk,
  basis: "estimated",
});

